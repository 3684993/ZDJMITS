// Offline audit of the pure projection module only. No service startup or network.
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const root = resolve(process.argv[2] ?? process.cwd());
const tsPath = process.argv[3];
if (!tsPath) throw new Error('Pass the inspected local typescript/lib/typescript.js path');
const ts = (await import(pathToFileURL(resolve(tsPath)).href)).default;
const file = 'apps/engine/src/services/s01TruthAccountingObservability.ts';
const source = readFileSync(resolve(root, file), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const m = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const checks = [];
const check = (id, expected, actual, passes) => checks.push({ id, expected, actual, passes });
const absent = { openOrderIdentity:false, fillIdentity:false, positionZero:true, checkedAt:100 };
let r = m.riskFactCoverage(absent);
check('A01_HISTORY_OMITTED', 'UNKNOWN when historyCovered is missing', r, r.status === 'UNKNOWN');
r = m.riskFactCoverage({ ...absent, historyCovered:true, checkedAt:1000, validUntil:999 });
check('A02_EXPIRED_BEFORE_CHECK', 'not CURRENT_NO_ACTIVE_RISK when validUntil < checkedAt', r, r.currentRisk !== 'CURRENT_NO_ACTIVE_RISK');
r = m.riskFactCoverage({ ...absent, positionZero:false, positionAttributed:true, historyCovered:true, validUntil:200 });
check('A03_ATTRIBUTED_POSITION', 'attributed position cannot prove no active risk', r, !['CURRENT_NO_ACTIVE_RISK','DURABLE_TERMINAL_PROVEN'].includes(r.currentRisk));
r = m.riskFactCoverage({ terminalStatus:'CANCELED', openOrderIdentity:true, fillIdentity:true, positionAttributed:true, historyCovered:true, checkedAt:100 });
check('A04_TERMINAL_CONFLICT', 'terminal status alone must not override active order/fill/position conflicts', r, !['CURRENT_NO_ACTIVE_RISK','DURABLE_TERMINAL_PROVEN'].includes(r.currentRisk));
const c = m.collectorWindowSummary({ segmentId:'s', identity:'i', startedAt:0, endedAt:600000, startCount:70, endCount:2, peak:70 });
check('A05_COUNTER_RESET', 'counter regression detected; no negative rate', c, c.ratePerHour === null && c.reset === true);
const p = m.primaryObservation({ paused:true, marketOpen:true, resourceFault:false, lastRunAt:null, now:100, maxIdleMs:10 });
check('A06_RUNTIME_PAUSE', 'cannot label every paused Primary as MARKET_PAUSE when market is open', p, p !== 'MARKET_PAUSE');
console.log(JSON.stringify({ sourceFile:file, sourceSha256Lf:createHash('sha256').update(source.replaceAll('\r\n','\n')).digest('hex'), tool:'typescript.transpileModule; pure exports only', checks, passed:checks.filter(x=>x.passes).length, failed:checks.filter(x=>!x.passes).length }, null, 2));
process.exitCode = checks.some(x=>!x.passes) ? 1 : 0;
